import { mkdirSync, writeFileSync, readFileSync, existsSync } from 'node:fs';
import { resolve, relative } from 'node:path';
import { command } from '../../../scripts/coverage/commands';
import { inputIdentity, hash } from '../../../scripts/coverage/source';
const root=process.cwd(), base=resolve(root,'.arc-verify/rust-coverage/integration');
const name=process.argv[2], argv=process.argv.slice(3);
if(!name || !argv.length) throw Error('expected label and exact command argv');
if(process.env.SKIP_COVERAGE) throw Error('SKIP_COVERAGE must be unset');
const dir=resolve(base,'runs',`${name}-${new Date().toISOString().replace(/[:.]/g,'-')}`);
mkdirSync(dir,{recursive:true});
const before=inputIdentity(root), env={...process.env};
const relevant=Object.fromEntries(Object.entries(env).filter(([k])=>/^(PATH|CARGO|RUST|LLVM|BUN|SKIP_COVERAGE|WORKSPACE_ROOT|ARC_)/.test(k)));
const started=Date.now();
const result=await command(argv,dir,root,env,600000);
const after=inputIdentity(root);
writeFileSync(resolve(dir,'stdout.txt'),result.stdout);writeFileSync(resolve(dir,'stderr.txt'),result.stderr);
const receipt={name,argv,cwd:root,pid:result.pid,started:result.started,ended:result.ended,durationMs:Date.now()-started,exit:result.exit,sourceHash:before.sha256,afterHash:after.sha256,sourceStable:before.sha256===after.sha256,inputs:before,environment:relevant,logs:{stdout:hash(result.stdout),stderr:hash(result.stderr)},directory:relative(root,dir)};
writeFileSync(resolve(dir,'receipt.json'),JSON.stringify(receipt,null,2)+'\n');
const index=resolve(base,'commands.json');
const prior=existsSync(index)?JSON.parse(readFileSync(index,'utf8')):[];
prior.push(receipt);writeFileSync(index,JSON.stringify(prior,null,2)+'\n');
console.log(JSON.stringify({name,exit:result.exit,durationMs:receipt.durationMs,sourceStable:receipt.sourceStable,directory:receipt.directory}));
console.log(result.stdout.slice(-4000));console.error(result.stderr.slice(-2000));
if(result.exit || !receipt.sourceStable) process.exitCode=1;
